/**
 * Stores the current keyboard input states.
 */
class Keyboard {
  /** @type {boolean} */
  LEFT = false;

  /** @type {boolean} */
  RIGHT = false;

  /** @type {boolean} */
  UP = false;

  /** @type {boolean} */
  DOWN = false;

  /** @type {boolean} */
  SPACE = false;

  /** @type {boolean} */
  D = false;

  /** @type {boolean} */
  S = false;
}
